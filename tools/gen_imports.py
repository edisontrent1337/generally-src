#!/usr/bin/env python3
"""Writes src/bridge/imports.h: the import address table slot of every function the exe imports.

Rewritten code calls imported functions (SDL, CRT, ...) through these slots, exactly like the original,
so the runtime's shims (and the shadow checker's purity rules) see the same calls.
"""
import os, re
import pefile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
pe = pefile.PE(os.path.join(ROOT, "game/orig/GeneRally.exe"))
# readable names for the C++ (mangled) MSVCP140 imports used by rewritten code
MANGLED = {
    "??6?$basic_ostream@DU?$char_traits@D@std@@@std@@QAEAAV01@M@Z": "ostream_insert_float",
    "??6?$basic_ostream@DU?$char_traits@D@std@@@std@@QAEAAV01@H@Z": "ostream_insert_int",
    "??6?$basic_ostream@DU?$char_traits@D@std@@@std@@QAEAAV01@I@Z": "ostream_insert_uint",
    "??6?$basic_ostream@DU?$char_traits@D@std@@@std@@QAEAAV01@P6AAAVios_base@1@AAV21@@Z@Z": "ostream_insert_manip",
    "?setw@std@@YA?AU?$_Smanip@_J@1@_J@Z": "setw",
    "?_Xout_of_range@std@@YAXPBD@Z": "Xout_of_range",
    "?setstate@?$basic_ios@DU?$char_traits@D@std@@@std@@QAEXH_N@Z": "ios_setstate",
    "?clear@?$basic_ios@DU?$char_traits@D@std@@@std@@QAEXH_N@Z": "ios_clear",
    "?read@?$basic_istream@DU?$char_traits@D@std@@@std@@QAEAAV12@PAD_J@Z": "istream_read",
    "?seekg@?$basic_istream@DU?$char_traits@D@std@@@std@@QAEAAV12@V?$fpos@U_Mbstatet@@@2@@Z": "istream_seekg_pos",
    "?seekg@?$basic_istream@DU?$char_traits@D@std@@@std@@QAEAAV12@_JH@Z": "istream_seekg",
    "?tellg@?$basic_istream@DU?$char_traits@D@std@@@std@@QAE?AV?$fpos@U_Mbstatet@@@2@XZ": "istream_tellg",
    "?write@?$basic_ostream@DU?$char_traits@D@std@@@std@@QAEAAV12@PBD_J@Z": "ostream_write",
    "?seekp@?$basic_ostream@DU?$char_traits@D@std@@@std@@QAEAAV12@V?$fpos@U_Mbstatet@@@2@@Z": "ostream_seekp_pos",
    "?seekp@?$basic_ostream@DU?$char_traits@D@std@@@std@@QAEAAV12@_JH@Z": "ostream_seekp",
    "?tellp@?$basic_ostream@DU?$char_traits@D@std@@@std@@QAE?AV?$fpos@U_Mbstatet@@@2@XZ": "ostream_tellp",
}
out = ["// generated by tools/gen_imports.py from the original exe: import address table slots", "#pragma once", ""]
for d in pe.DIRECTORY_ENTRY_IMPORT:
    dll = d.dll.decode()
    out.append("// %s" % dll)
    for imp in d.imports:
        if not imp.name:
            continue
        name = imp.name.decode()
        ident = name if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) else MANGLED.get(name)
        if ident is None:
            continue  # C++ mangled MSVCP names: add by hand where needed
        out.append("constexpr uint32_t IMP_%s = 0x%x;" % (ident, imp.address))
    out.append("")
open(os.path.join(ROOT, "src/bridge/imports.h"), "w").write("\n".join(out))
